/** Simulated measured duration of a generated voice chunk (deterministic). */
export function measureAudio(projectId, chunk, version) {
  const r = seeded(`${projectId}:${chunk.id}:${version}`)
  const offset = Math.round((r - 0.45) * 14)
  // First take of chunk 03 runs long so the 60–90 s exception acknowledgment is part of every demo.
  if (chunk.id === '03' && version === 1) return chunk.targetSeconds + 16
  return Math.max(20, chunk.targetSeconds + (version > 1 ? Math.min(offset, 2) : offset))
}

export const AUDIO_SAMPLES = 6
export function audioSampleFor(project, chunkId) {
  const n = ((parseInt(chunkId, 10) - 1) % AUDIO_SAMPLES) + 1
  return `${import.meta.env?.BASE_URL ?? '/'}samples/${isArabic(project) ? 'voice-ar' : 'voice-en'}-${pad2(n)}.m4a`
}

