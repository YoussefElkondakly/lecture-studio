/** Storyboard scenes derived from canonical content and target duration. */
export function generateStoryboard(project, contentVersion, version, { feedback, targetScenes } = {}) {
  const ar = isArabic(project) && topicFor(project.source) === 'jaundice'
  const t = ar ? { ...topicData(project), ...AR_JAUNDICE } : topicData(project)
  const total = project.plan.totalSeconds
  const raw = [
    { heading: ar ? 'المقدمة' : 'Opening', onScreen: project.title, visual: 'Title card with lecture name and a calm illustration motif.' },
    { heading: ar ? 'أهداف التعلم' : 'Learning objectives', onScreen: t.objectives[0], visual: 'Three objectives revealed one by one.' },
    ...t.sections.map(([h, b]) => ({ heading: h, onScreen: h, visual: `Diagram slide summarising: ${b.slice(0, 90)}…` })),
    { heading: ar ? 'الجدول' : 'Key table', onScreen: ar ? 'ملخص الجدول' : 'Summary table', visual: 'Table rebuilt as a clean slide; values marked as placeholders.' },
    { heading: ar ? 'الخلاصة' : 'Summary', onScreen: ar ? 'الخلاصة' : 'Take-home points', visual: 'Recap of objectives with the clinic contact reminder.' },
  ]
  const per = Math.floor(total / raw.length)
  const scenes = raw.map((s, i) => {
    const id = `S${pad2(i + 1)}`
    const revised = version > 1 && (targetScenes?.length ? targetScenes.includes(id) : i === 2)
    return {
      id,
      ...s,
      seconds: i === raw.length - 1 ? total - per * (raw.length - 1) : per,
      notes: revised ? `Revised in v${version}${feedback ? ` — ${feedback}` : ''}` : '',
      palette: i % 3,
    }
  })
  return scenes
}

