/** Narration transcript text for one chunk. */
export function generateTranscript(project, chunk, version, { feedback } = {}) {
  const ar = isArabic(project)
  const pool = ar ? AR_LINES : EN_LINES
  const wpm = ar ? 110 : 145
  const targetWords = Math.round((chunk.targetSeconds * wpm) / 60)
  const mode = project.prefs.speakerMode
  const speakers = mode === 'ONE' ? null : mode === 'TWO' ? ['Lecturer', 'Resident'] : ['Lecturer', 'Resident', 'Nurse educator']
  const speakersAr = { Lecturer: 'المحاضر', Resident: 'الطبيب المقيم', 'Nurse educator': 'الممرضة' }
  const lines = []
  let words = 0
  let i = parseInt(chunk.id, 10) * 3 + version
  let turn = 0
  if (version > 1) {
    const note = ar ? 'تم تعديل هذا الجزء بناءً على ملاحظات المراجعة.' : 'This part has been revised following review feedback.'
    lines.push(speakers ? `${ar ? speakersAr[speakers[0]] : speakers[0]}: ${note}` : note)
    words += note.split(/\s+/).length
  }
  while (words < targetWords) {
    const sentence = pool[i % pool.length]
    if (speakers) {
      const sp = speakers[turn % speakers.length]
      lines.push(`${ar ? speakersAr[sp] : sp}: ${sentence}`)
      turn++
    } else {
      lines.push(sentence)
    }
    words += sentence.split(/\s+/).length
    i++
  }
  void feedback
  return speakers ? lines.join('\n') : lines.join(' ')
}

export function wordCount(text) {
  return text.trim().split(/\s+/).filter(Boolean).length
}

export function estimateSeconds(project, text) {
  const wpm = isArabic(project) ? 110 : 145
  return Math.round((wordCount(text.replace(/^[^:\n]{1,30}:\s/gm, '')) / wpm) * 60)
}

